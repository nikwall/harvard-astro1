"""Copy the lesson content and figures from the study guide source into the app.

Run from the repo root:  python scripts/sync_content.py [path/to/study_guide_src]
The study guide is the single source for the lesson text; edit it there and re-run this script.
"""
import glob
import html as htmllib
import json
import os
import re
import shutil
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "..", "course work", "study_guide_src")


def text(s):
    return htmllib.unescape(re.sub(r"\s+", " ", re.sub(r"<[^>]+>", "", s))).strip()


manifest = {}
for f in sorted(glob.glob(os.path.join(SRC, "content", "ch*.html"))) + [os.path.join(SRC, "content", "z90_appendix.html")]:
    html = open(f, encoding="utf-8").read()
    html = html.replace('src="../figs/', 'src="figs/')
    html = re.sub(r"<!-- ADD:(START|END) -->\n?", "", html)
    # The lesson files are fragments that the app loads. If a crawler opens one directly, this tag
    # (which the HTML parser puts into the implied <head>) keeps it out of search engines.
    html = '<meta name="robots" content="noindex, nofollow">\n' + html
    name = "appendix.html" if "appendix" in f else os.path.basename(f)
    open(os.path.join(ROOT, "content", name), "w", encoding="utf-8", newline="\n").write(html)
    print("content/" + name)
    if name.startswith("ch"):
        # The lesson's page list: one page per <h2>, in order (the app splits the chapter the same way).
        secs = []
        for m in re.finditer(r'<h2([^>]*)>\s*<span class="k">(.*?)</span>(.*?)</h2>', html, re.S):
            attrs, k, t = m.group(1), text(m.group(2)), text(m.group(3))
            kind = "practice" if k.lower().startswith("practice") else ("further" if "more" in attrs else "section")
            secs.append({"kind": kind, "key": k if kind == "section" else kind, "title": t})
        bigq = re.search(r'<div class="bigq">(.*?)</div>', html, re.S)
        pp = re.search(r"Book pp\. ([\d–-]+)", html)
        manifest[name[:-5]] = {
            "bigq": text(bigq.group(1)).replace("Big question: ", "") if bigq else "",
            "bookPages": pp.group(1) if pp else "",
            "sections": secs,
        }

with open(os.path.join(ROOT, "js", "manifest.js"), "w", encoding="utf-8", newline="\n") as out:
    out.write("/* Generated by scripts/sync_content.py: the page list of every lesson. Do not edit by hand. */\n")
    out.write("window.MANIFEST = " + json.dumps(manifest, ensure_ascii=False, indent=1) + ";\n")
print("js/manifest.js")

for f in glob.glob(os.path.join(SRC, "figs", "*.svg")):
    shutil.copy(f, os.path.join(ROOT, "figs", os.path.basename(f)))
print(len(glob.glob(os.path.join(ROOT, "figs", "*.svg"))), "figures")

kx = os.path.join(SRC, "node_modules", "katex", "dist")
if os.path.isdir(kx):
    out = os.path.join(ROOT, "vendor", "katex")
    for n in ["katex.min.css", "katex.min.js", "contrib/auto-render.min.js"]:
        shutil.copy(os.path.join(kx, n), os.path.join(out, os.path.basename(n)))
    for w in glob.glob(os.path.join(kx, "fonts", "*.woff2")):
        shutil.copy(w, os.path.join(out, "fonts", os.path.basename(w)))
    print("katex copied")
