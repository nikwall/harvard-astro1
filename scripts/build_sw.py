"""Write sw.js: the service worker that makes Harvard ASTRO1 installable and usable offline.

    python scripts/build_sw.py

Run it after adding, removing or changing files, so the offline copy that installed apps keep is
refreshed (the version is a hash of every listed file). Forgetting it is harmless while online:
pages, code and data are fetched network-first anyway."""
import hashlib
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
INCLUDE_DIRS = ["css", "js", "content", "figs", "data", "vendor", "icons"]
INCLUDE_FILES = ["index.html", "manifest.webmanifest", "favicon.svg"]
SKIP_EXT = {".md", ".txt", ".py", ".gitkeep"}

TEMPLATE = """/* Service worker for Harvard ASTRO1: makes the app installable and keeps a full offline copy.
   GENERATED by scripts/build_sw.py; don't edit by hand, run the script instead. */
const VERSION = "__VERSION__";
const CACHE = "astro1-" + VERSION;
const PRECACHE = __LIST__;

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE)
      .then((cache) => cache.addAll(PRECACHE.map((u) => new Request(u, { cache: "reload" }))))
      .then(() => self.skipWaiting())
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith("astro1-") && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

// Pages, code and data: network first (always fresh when online), cached copy when offline.
// Fonts, figures, icons: cache first. Other sites (counter, YouTube, sky chart): never touched.
self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;
  const fresh = req.mode === "navigate" || /\\/$|\\.(html|js|css|json|webmanifest)$/.test(url.pathname);
  if (fresh) {
    event.respondWith(
      fetch(req)
        .then((res) => { if (res.ok) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(req, copy)); } return res; })
        .catch(() => caches.match(req, { ignoreSearch: true }).then((hit) => hit || (req.mode === "navigate" ? caches.match("index.html") : Response.error())))
    );
  } else {
    event.respondWith(
      caches.match(req, { ignoreSearch: true }).then((hit) => hit || fetch(req).then((res) => {
        if (res.ok) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(req, copy)); }
        return res;
      }))
    );
  }
});
"""


def main():
    files = list(INCLUDE_FILES)
    for d in INCLUDE_DIRS:
        for base, _, names in os.walk(os.path.join(ROOT, d)):
            for n in names:
                if os.path.splitext(n)[1] in SKIP_EXT or n.startswith("."):
                    continue
                files.append(os.path.relpath(os.path.join(base, n), ROOT).replace(os.sep, "/"))
    files = sorted(set(files))
    h = hashlib.sha1()
    for f in files:
        h.update(f.encode())
        with open(os.path.join(ROOT, f), "rb") as fh:
            h.update(fh.read())
    listing = ["./"] + files
    body = TEMPLATE.replace("__VERSION__", h.hexdigest()[:12]).replace("__LIST__", json.dumps(listing, indent=0).replace("\n", " "))
    with open(os.path.join(ROOT, "sw.js"), "w", encoding="utf-8", newline="\n") as out:
        out.write(body)
    size = sum(os.path.getsize(os.path.join(ROOT, f)) for f in files)
    print(f"sw.js: {len(listing)} files, {size / 1e6:.1f} MB offline, version {h.hexdigest()[:12]}")


if __name__ == "__main__":
    main()
